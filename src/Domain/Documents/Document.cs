using DocOps.Domain.Common;
using DocOps.Domain.Compliance;
using DocOps.Domain.Tenancy;

namespace DocOps.Domain.Documents;

/// <summary>
/// A document in the repository: the metadata, state and access rules. The file content itself lives
/// in <see cref="DocumentVersion"/> and in the file store, never in this row (see ADR-003).
/// </summary>
public sealed class Document : TenantEntity, ISoftDeletable
{
    public required string Title { get; set; }

    /// <summary>Human-readable identifier shown to users and quoted in e-mails, e.g. "DOC-2026-00042".</summary>
    public required string Reference { get; set; }

    public string? Summary { get; set; }

    public Guid DocumentTypeId { get; set; }
    public DocumentType? DocumentType { get; set; }

    public DocumentStatus Status { get; set; } = DocumentStatus.Draft;

    public Guid OwnerUserId { get; set; }

    public Guid? DepartmentId { get; set; }
    public Department? Department { get; set; }

    /// <summary>Legal entity the document belongs to, for groups that operate several companies.</summary>
    public string? BusinessEntity { get; set; }

    public SecurityClassification Classification { get; set; } = SecurityClassification.Internal;

    /// <summary>Denormalised from the current version so document lists never need to join versions.</summary>
    public int CurrentVersionNumber { get; set; }

    /// <summary>
    /// Id of the version flagged <see cref="DocumentVersion.IsCurrent"/>. Deliberately not a foreign
    /// key: a constraint in both directions between a document and its version would create a
    /// circular reference that SQL Server cannot resolve on delete.
    /// </summary>
    public Guid? CurrentVersionId { get; set; }

    public Guid? RetentionPolicyId { get; set; }
    public RetentionPolicy? RetentionPolicy { get; set; }

    /// <summary>When the retention period expires. Calculated from the policy at archive time.</summary>
    public DateTimeOffset? RetentionDueAtUtc { get; set; }

    public DateTimeOffset? ArchivedAtUtc { get; set; }

    /// <summary>Status the document held before archiving, so a restore returns it to where it was.</summary>
    public DocumentStatus? PreArchiveStatus { get; set; }

    /// <summary>Set by the workflow engine once an instance is running against this document (Phase 3).</summary>
    public Guid? ActiveWorkflowInstanceId { get; set; }

    public ICollection<DocumentVersion> Versions { get; set; } = [];
    public ICollection<DocumentTag> Tags { get; set; } = [];
    public ICollection<DocumentMetadataValue> MetadataValues { get; set; } = [];
    public ICollection<DocumentPermission> Permissions { get; set; } = [];

    public bool IsDeleted { get; set; }
    public DateTimeOffset? DeletedAtUtc { get; set; }
    public Guid? DeletedByUserId { get; set; }
}

/// <summary>
/// An immutable snapshot of the document's content. Updating content never overwrites a version: it
/// adds one, so the history can always be reconstructed.
/// </summary>
public sealed class DocumentVersion : TenantEntity
{
    public Guid DocumentId { get; set; }
    public Document? Document { get; set; }

    public int VersionNumber { get; set; }

    /// <summary>Key in the file store. Generated by the server; never derived from user input.</summary>
    public required string StorageKey { get; set; }

    public required string FileName { get; set; }
    public required string ContentType { get; set; }
    public long FileSizeBytes { get; set; }

    /// <summary>SHA-256 of the stored bytes: integrity check, duplicate detection and signature evidence.</summary>
    public required string ContentHash { get; set; }

    public string? Comment { get; set; }

    /// <summary>
    /// Plain text extracted from the file, used by full-text search and by the demo AI provider.
    /// Null when the format is not text-extractable.
    /// </summary>
    public string? ExtractedText { get; set; }

    public bool IsCurrent { get; set; }
}
